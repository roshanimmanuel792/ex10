// Ex.10 - Developing Server-Side Application Using Node.js
// CarePlus Medical Appointment System - simple HTTP server using the built-in http module

const http = require('http');

const PORT = 3000;

// show the request URL as plain text, never as HTML
function escapeHtml(text) {
    return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// common page layout used by every route
function page(title, body, req) {
    return `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${title} - CarePlus</title>
    <style>
        * { box-sizing: border-box; }
        body { margin: 0; font-family: "Public Sans", "Segoe UI", Arial, sans-serif; line-height: 1.55; background: #f2f5f7; color: #16263a; }
        main { max-width: 900px; margin: auto; padding: 40px 24px; }
        header { display: flex; justify-content: space-between; align-items: center; flex-wrap: wrap; gap: 16px; margin-bottom: 28px; }
        .brand { display: flex; align-items: center; gap: 12px; font-size: 20px; font-weight: 800; }
        .brand i { width: 40px; height: 40px; border-radius: 9px; background: #d64545; color: #fff; font-style: normal; font-size: 30px; line-height: 40px; text-align: center; }
        .brand small { display: block; font-size: 12.5px; font-weight: 500; color: #5d6f80; }
        nav a { color: #16263a; text-decoration: none; font-weight: 600; margin-left: 20px; }
        nav a:hover { color: #2e7d6b; }
        .sheet { background: #fff; border: 1px solid #dce3e9; border-radius: 10px; padding: 36px 40px; }
        h1 { margin: 0 0 6px; font-size: 34px; letter-spacing: -0.02em; }
        .sub { margin: 0 0 18px; color: #5d6f80; font-size: 17px; }
        ul { padding-left: 20px; }
        .readout { display: flex; margin-top: 26px; background: #16263a; border-radius: 8px; color: #fff; }
        .readout div { flex: 1; padding: 16px 20px; }
        .readout div + div { border-left: 1px solid #2e4660; }
        .readout small { display: block; font-size: 13px; color: #8fa2b4; }
        .readout span { display: block; font-size: 26px; font-weight: 700; color: #9ad9c4; overflow-wrap: anywhere; }
        .btn { display: inline-block; margin-top: 8px; padding: 11px 22px; background: #2e7d6b; color: #fff; text-decoration: none; font-weight: 600; border-radius: 6px; }
        footer { padding: 24px 0; color: #5d6f80; font-size: 14px; }
        @media (max-width: 600px) { nav a { margin: 0 16px 0 0; } .sheet { padding: 24px 20px; } .readout { flex-direction: column; } .readout div + div { border-left: 0; border-top: 1px solid #2e4660; } }
    </style>
</head>
<body>
    <main>
        <header>
            <div class="brand"><i>+</i><span>CarePlus<small>Medical Appointment System</small></span></div>
            <nav>
                <a href="/">Welcome</a>
                <a href="/home">Home</a>
                <a href="/about">About</a>
            </nav>
        </header>
        <div class="sheet">
            ${body}
            <div class="readout">
                <div><small>Request URL</small><span>${escapeHtml(req.url)}</span></div>
                <div><small>Request Method</small><span>${req.method}</span></div>
            </div>
        </div>
        <footer>CarePlus, Medical Appointment System</footer>
    </main>
</body>
</html>`;
}

const server = http.createServer((req, res) => {
    let status = 200;
    let html;

    if (req.url === '/') {
        html = page('Welcome', `
            <h1>Welcome to Node.js!</h1>
            <p class="sub">This is a server-side application.</p>
            <p>This page is generated by a Node.js server for the CarePlus Medical Appointment System. Every request is handled
               by <b>http.createServer()</b> and the HTML is sent back using <b>res.end()</b>.</p>
            <a class="btn" href="/home">Go to Home</a>`, req);
    } else if (req.url === '/home') {
        html = page('Home', `
            <h1>CarePlus Home</h1>
            <p class="sub">Book a doctor appointment online</p>
            <p>Appointments you can book today:</p>
            <ul>
                <li>General medicine, 9 AM to 1 PM</li>
                <li>Cardiology specialist, Monday to Friday</li>
                <li>Paediatrics and vaccinations, 4 PM to 8 PM</li>
            </ul>`, req);
    } else if (req.url === '/about') {
        html = page('About', `
            <h1>About CarePlus</h1>
            <p class="sub">Online doctor appointments for clinics in Coimbatore, Tamil Nadu</p>
            <p>CarePlus lets patients book, reschedule and cancel doctor appointments without waiting
               in a queue. 12 doctors across 6 departments take bookings every day.</p>
            <p>Clinic hours: 9 AM to 1 PM and 4 PM to 8 PM.</p>`, req);
    } else {
        status = 404;
        html = page('Not Found', `
            <h1>404 - Page Not Found</h1>
            <p class="sub">The page you requested does not exist on this server.</p>
            <a class="btn" href="/">Back to Welcome</a>`, req);
    }

    res.writeHead(status, {
        'Content-Type': 'text/html'
    });
    res.end(html);

    console.log(`${req.method} ${req.url} - ${status}`);
});

server.listen(PORT, () => {
    console.log(`Server running at http://localhost:${PORT}`);
});
